# ==================== API helpers ====================

def get_aircraft_by_id(aircraft_id: str) -> Optional[Dict[str, Any]]:
    """Получить данные самолёта по ID."""
    for ac in AIRCRAFTS:
        if ac["id"] == aircraft_id:
            return ac
    return None


def list_aircrafts() -> List[Dict[str, Any]]:
    """Список всех самолётов (без детального контента разделов)."""
    return [
        {
            "id": ac["id"],
            "name": ac["name"],
            "designation": ac["designation"],
            "description": ac["description"],
            "image_emoji": ac["image_emoji"],
            "sections_count": len(ac["sections"]),
        }
        for ac in AIRCRAFTS
    ]


def get_aircraft_sections(aircraft_id: str) -> Optional[List[Dict[str, Any]]]:
    """Получить все разделы РЛЭ для конкретного самолёта."""
    ac = get_aircraft_by_id(aircraft_id)
    if not ac:
        return None
    return [
        {
            "id": s["id"],
            "title": s["title"],
            "icon": s["icon"],
            "content": s["content"],
            "details": s["details"],
        }
        for s in ac["sections"]
    ]


def get_aircraft_section(aircraft_id: str, section_id: str) -> Optional[Dict[str, Any]]:
    """Получить один конкретный раздел РЛЭ."""
    sections = get_aircraft_sections(aircraft_id)
    if not sections:
        return None
    for s in sections:
        if s["id"] == section_id:
            return s
    return None
